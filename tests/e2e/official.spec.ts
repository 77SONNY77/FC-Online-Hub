test('probability API is paginated, exact, isolated and rejects invalid requests', async ({ request, page }) => {
  const product = (await (await request.get('/api/products/official-44699')).json()).data;
  expect(product.metadata).toMatchObject({ source: 'OFFICIAL_WEB', dataType: 'OFFICIAL', verificationStatus: 'VERIFIED' });
  expect(product.fieldVerification.components).toBe('VERIFIED');
  expect(product.components.map((c: { quantity: number }) => c.quantity)).toEqual([1, 3, 30]);
  expect(product.components[0].children).toHaveLength(5);
  expect(JSON.stringify(product)).not.toContain('TOP 750');
  const root = '/api/items/official-item-24987-v1/probabilities';
  const first = await (await request.get(root)).json();
  expect(first.pagination).toMatchObject({ pageSize: 50, total: 750, pages: 15 });
  expect(first.entries).toHaveLength(50); expect(first.entries[0].rank).toBe(1);
  const last = await (await request.get(root + '?page=15')).json();
  expect(last.entries.at(-1).rank).toBe(750);
  expect((await request.get(root + '?page=16')).status()).toBe(404);
  expect((await request.get(root + '?page=-1')).status()).toBe(400);
  expect((await request.get('/api/items/demo-box-v1/probabilities')).status()).toBe(404);
  await page.goto('/items/official-item-24987-v1/probabilities');
  await expect(page.locator('tbody tr')).toHaveCount(50);
  await page.getByRole('link', { name: '다음 페이지', exact: true }).click();
  await expect(page.locator('tbody tr').first()).toContainText('TOP 51');
});
